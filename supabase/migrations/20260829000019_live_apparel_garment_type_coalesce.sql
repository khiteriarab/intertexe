    m.brand_name,
    m.name,
    m.product_id,
    m.url,
    m.image_url,
    m.price,
    m.composition,
    m.natural_fiber_percent,
    m.category,
    m.approved,
    m.created_at,
    m.matching_set_id,
    m.is_sale,
    m.original_price,
    m.barcode,
    m.upc,
    m.ean,
    m.sku,
    m.qr_code,
    m.retailer,
    m.material_summary,
    m.intertexe_quality_status,
    m.scan_count,
    m.last_scanned_at,
    m.tags,
    m.collection_slugs,
    m.editorial_categories,
    m.material_metadata,
    m.added_at,
    m.updated_at,
    m.currency,
    m.retailer_country,
    m.raw_price,
    m.retailer_mid,
    m.feed_source,
    m.feed_url,
    m.last_seen_at,
    m.is_active,
    m.region,
