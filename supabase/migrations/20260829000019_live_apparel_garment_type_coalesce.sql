    m.dpp_record_url,
    m.sustainability_certifications,
    m.manufacturer_name,
    m.manufacturer_country,
    m.material_source,
    m.end_of_life_instructions,
    m.color_normalized,
    m.retailer_name,
    m.discount_percent,
    m.size_options,
    m.product_url_us,
    m.product_url_uk,
    m.price_changed_at,
    m.is_displayable,
    coalesce(p.garment_type, m.garment_type) AS garment_type,
    p.is_editor_pick,
    p.editor_picked_at
   FROM live_products_apparel_mat m
     LEFT JOIN products p ON p.id = m.id;

